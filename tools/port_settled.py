#!/usr/bin/env python3
"""The proven-unused list and the doubts list of a ported build, in the Japanese convention (docs §1.5; HOWTO_NEW_ROM.md section 0.1).

  tools/port_settled.py --tag us|gold [--check]

Reads the final names table roms/<folder>/disasm/sym_names_<tag>.csv and writes, beside it:
  sym_settled_unused_<tag>.csv  every name tagged I: in a ported build an I name is a claim that something is unused, dead, unreferenced or
                                never loaded (or its Japanese counterpart is such a name), which rests on the absence of evidence
                                (tools/port_evidence_tags.py), so its tag is final, as for the Japanese sym_settled_unused_jp.csv.
                                Columns of the Japanese list: bank, addr, name, conf, group (dead code: a traced dead root; unused data;
                                as in the Japanese ROM: its Japanese label is I), size (bytes to the next label of the bank), evidence (the note), proof (the layer).
  sym_unconclusive_<tag>.csv    the doubts: every name tagged ? (none so far: the file then holds its header only), Japanese columns
  sym_unconclusive_<tag>.md     the same as a page
--check compares the three files with a fresh run and exits 1 when one differs (the consistency checker runs it).
"""
import argparse, csv, io, os, sys
FOLDER = {'us': 'us_eu', 'gold': 'gold'}
ap = argparse.ArgumentParser(); ap.add_argument('--tag', required=True, choices=sorted(FOLDER)); ap.add_argument('--check', action='store_true')
a = ap.parse_args(); T = a.tag; D = os.path.join('roms', FOLDER[T], 'disasm')
rows = list(csv.DictReader(open(os.path.join(D, 'sym_names_%s.csv' % T), encoding='utf-8')))
key = lambda r: (int(r['bank'], 16), int(r['addr'], 16))
rows.sort(key=key)
nxt = {}
for i, r in enumerate(rows):
    b, ad = key(r); end = 0x4000 if b == 0 else 0x8000
    if i + 1 < len(rows) and key(rows[i + 1])[0] == b: end = key(rows[i + 1])[1]
    nxt[(b, ad)] = end - ad
import json
CODE = {tuple(int(x, 16) for x in k.split(':')) for k, n in json.load(open(os.path.join('roms', FOLDER[T], 'trace', 'trace_%s.json' % T)))['code'].items() if n > 0}
def group(r):
    n = (r['note'] or '').lower()
    if 'japanese label' in n or 'japanese counterpart' in n: return 'as in the Japanese ROM'
    return 'dead code' if key(r) in CODE else 'unused data'        # a dead root is traced (its code is proven, nothing reaches it)
def text(cols, rs):
    s = io.StringIO(); w = csv.DictWriter(s, cols, lineterminator='\n'); w.writeheader(); w.writerows(rs); return s.getvalue()
SCOL = ['bank', 'addr', 'name', 'conf', 'group', 'size', 'evidence', 'proof']
settled = [dict(bank=r['bank'], addr=r['addr'], name=r['name'], conf=r['conf'], group=group(r), size=nxt[key(r)], evidence=r['note'], proof=r['source'])
           for r in rows if r['conf'] == 'I']
DCOL = ['bank', 'addr', 'name', 'conf', 'group', 'size', 'best_guess', 'evidence', 'why_doubtful', 'what_would_settle_it']
doubt = [dict(bank=r['bank'], addr=r['addr'], name=r['name'], conf=r['conf'], group='', size=nxt[key(r)], best_guess='', evidence=r['note'], why_doubtful='', what_would_settle_it='')
         for r in rows if r['conf'] == '?']
title = {'us': 'Game Boy Camera (USA, Europe)', 'gold': 'Game Boy Camera Gold (USA)'}[T]
md = ['# %s: doubtful names\n' % title, 'Generated by `tools/port_settled.py --tag %s` from `sym_names_%s.csv`.\n' % (T, T),
      '**%d doubtful names** (tag `?`).' % len(doubt) + (' Nothing is open.' if not doubt else ''), '',
      'Not counted above: %d names tagged I whose tag is final, the claims that something is unused, dead or never loaded (they rest on the absence '
      'of evidence, as the Japanese convention says); they are listed with their evidence in `sym_settled_unused_%s.csv`.' % (len(settled), T)]
if doubt:
    md += ['', '| address | name | evidence |', '|---|---|---|'] + ['| %s:%s | `%s` | %s |' % (r['bank'], r['addr'], r['name'], r['evidence'].replace('|', '/')) for r in doubt]
out = {os.path.join(D, 'sym_settled_unused_%s.csv' % T): text(SCOL, settled), os.path.join(D, 'sym_unconclusive_%s.csv' % T): text(DCOL, doubt),
       os.path.join(D, 'sym_unconclusive_%s.md' % T): '\n'.join(md) + '\n'}
bad = 0
for f, t in out.items():
    if a.check:
        if not os.path.exists(f) or open(f, encoding='utf-8').read() != t: print('stale: %s (rerun tools/port_settled.py --tag %s)' % (f, T)); bad = 1
    else: open(f, 'w', encoding='utf-8').write(t)
print('%s: %d settled unused (I), %d doubtful (?)%s' % (T, len(settled), len(doubt), ' (check)' if a.check else ''))
sys.exit(bad)
