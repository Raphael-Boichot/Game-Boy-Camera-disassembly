#!/usr/bin/env python3
"""Doubts list of the Hello Kitty symbol file: roms/hello_kitty/disasm/sym_unconclusive_kitty.{csv,md} (generated).

  tools/kitty_doubts.py [--check]

Every name of disasm/sym_names_kitty.csv tagged I or ? must have one row in the hand table disasm/doubts_groups_kitty.csv
(the data names of tools/kitty_data_names.py get their group from their source: `forced only` / `not run`; its leftovers go to
sym_settled_unused_kitty.csv, not to the doubts list)
(bank, addr, group, why, settle; group = forced only / not run / unused) and every row of that table must be such a name: the
script stops otherwise. Group `unused` is a final verdict (nothing can reach the code, the tag stays I): as in the Japanese ROM, the
master (tools/make_doubts.py, status `final`; owner 2026-11-15: "Japanese ROM is the master. Follow its rules"), those rows leave the
doubts list, are not counted as doubtful and go to sym_settled_unused_kitty.csv (with their size and proof) and to the last section of the md.
--check compares the two outputs with a fresh run instead of writing them (exit 1 when they differ).
"""
import csv, os, sys, collections, io
KD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'roms', 'hello_kitty', 'disasm')
names = list(csv.DictReader(open(os.path.join(KD, 'sym_names_kitty.csv'), encoding='utf-8')))
def leftover(r): return r['source'] == 'data_left' or (r['name'].startswith('Leftover_') and r['source'].startswith('hand'))   # + the hand-read ones (2026-11-15)
doubt = {(r['bank'], r['addr']): r for r in names if r['conf'] != 'C' and not leftover(r)}
settled = [r for r in names if leftover(r)]                       # the leftovers (owner rule 2026-11-11): final, not doubtful
G = {(r['bank'], r['addr']): r for r in csv.DictReader(open(os.path.join(KD, 'doubts_groups_kitty.csv'), encoding='utf-8'))}
AUTO = {'data': ('forced only', 'its bytes are read only in forced runs (state pokes), not in an organic run', 'an organic run (core or BGB) that reads them'),
        'data_entry': ('not run', 'no run reads its bytes; a table of the same bank points to it (the word in the evidence)', 'a run that reaches the entry of that table')}
for k, r in doubt.items():                    # the data names of tools/kitty_data_names.py carry their group (no hand row)
    if r['source'] in AUTO and k not in G: G[k] = dict(zip(('group', 'why', 'settle'), AUTO[r['source']]))
miss = [k for k in doubt if k not in G]; extra = [k for k in G if k not in doubt]
if miss or extra:
    sys.exit('kitty_doubts: no group row for %s; group rows without a doubtful name: %s' % (' '.join('%s:%s' % k for k in miss) or '-', ' '.join('%s:%s' % k for k in extra) or '-'))
ORDER = ['forced only', 'not run', 'unused']
OPEN = ORDER[:2]
bad = [g['group'] for g in G.values() if g['group'] not in ORDER]
if bad: sys.exit('kitty_doubts: unknown group %s' % bad)
rows = sorted((dict(bank=k[0], addr=k[1], name=doubt[k]['name'], conf=doubt[k]['conf'], group=G[k]['group'], evidence=doubt[k]['note'], why_doubtful=G[k]['why'],
               what_would_settle_it=G[k]['settle']) for k in doubt), key=lambda x: (ORDER.index(x['group']), x['bank'], x['addr']))
NEXT = collections.defaultdict(list)                                # the size of a name: up to the next name of its bank (the Japanese size column)
for r in names: NEXT[r['bank']].append(int(r['addr'], 16))
for v in NEXT.values(): v.sort()
def size(b, a):
    a = int(a, 16); nx = [x for x in NEXT[b] if x > a]; return (nx[0] if nx else 0x8000 if a >= 0x4000 else 0x4000) - a
unused = [x for x in rows if x['group'] == 'unused']; rows = [x for x in rows if x['group'] != 'unused']
c = io.StringIO(); w = csv.DictWriter(c, fieldnames=list(rows[0]) if rows else ['bank'], lineterminator='\n'); w.writeheader(); w.writerows(rows)
n = collections.Counter(x['group'] for x in rows)
tags = collections.Counter(r['conf'] for r in names)
L = ['# Doubtful names of the Hello Kitty symbol file\n',
     'Generated by `tools/kitty_doubts.py` from `sym_names_kitty.csv` and the hand table `doubts_groups_kitty.csv` (companion: `sym_unconclusive_kitty.csv`). '
     'Every name not tagged C is here, except the leftovers (`Leftover_BB_AAAA`, tag I, final, owner rule 2026-11-11) and the names proven unused: %d of %d names (C %d / I %d / ? %d), %d in modes reached only by forcing the mode byte, %d in states the runs did not reach.\n' % (
     len(rows), len(names), tags['C'], tags['I'], tags['?'], n['forced only'], n['not run']),
     'Not counted above: %d rows proven unused, whose tag is final (I: the verdict is that nothing uses them, so no run or screen can confirm it; `doubts_groups_kitty.csv`, group `unused`, as the Japanese ROM\'s status `final`); they are listed with the proof in the last section and in `sym_settled_unused_kitty.csv`, with the %d leftovers.\n' % (len(unused), len(settled)),
     'The code of every row is read: what each routine does is in the evidence column; the doubt is whether and where the game runs it.\n']
for g in OPEN:
    X = [x for x in rows if x['group'] == g]
    if not X: continue
    L.append('## %s (%d)\n' % (g, len(X)))
    L.append('| address | name | evidence | why doubtful | what would settle it |\n|---|---|---|---|---|')
    for x in X: L.append('| %s:%s | `%s` | %s | %s | %s |' % (x['bank'], x['addr'], x['name'], x['evidence'].replace('|', '/'), x['why_doubtful'], x['what_would_settle_it']))
    L.append('')
if unused:
    L.append('## settled as unused, final I (%d)\n' % len(unused))
    L.append('_Why not doubtful:_ the name and the kind are not in question and nothing can reach them; nothing more can be learnt about them.\n')
    L.append('| address | name | bytes | group it left | proof |\n|---|---|---|---|---|')
    for x in unused: L.append('| %s:%s | `%s` | %d | unused | %s |' % (x['bank'], x['addr'], x['name'], size(x['bank'], x['addr']), x['why_doubtful'].replace('|', '/')))
    L.append('')
md = '\n'.join(L)
c2 = io.StringIO(); w2 = csv.writer(c2, lineterminator='\n'); w2.writerow(['bank', 'addr', 'name', 'conf', 'group', 'size', 'evidence', 'proof'])
for x in unused:
    w2.writerow([x['bank'], x['addr'], x['name'], x['conf'], 'unused', size(x['bank'], x['addr']), x['evidence'], x['why_doubtful'] + ' (doubts_groups_kitty.csv, group unused)'])
for r in settled:
    w2.writerow([r['bank'], r['addr'], r['name'], r['conf'], 'leftover', int(r['note'].split(' bytes')[0].split()[-1]), r['note'],
                 'tools/kitty_data_names.py: no run (core, BGB, core paths, forced) reads or executes these bytes, no code names their address, no table of the bank points to them'
                 if r['source'] == 'data_left' else 'hand reading (%s): the bytes before the first label of the bank; no run (core, BGB, core paths, forced) reads them, no proven instruction of the bank loads an address inside them' % r['source']])
out = {os.path.join(KD, 'sym_unconclusive_kitty.csv'): c.getvalue(), os.path.join(KD, 'sym_unconclusive_kitty.md'): md, os.path.join(KD, 'sym_settled_unused_kitty.csv'): c2.getvalue()}
if '--check' in sys.argv:
    stale = [p for p, t in out.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != t]
    print('kitty_doubts: %s' % ('stale: ' + ' '.join(os.path.basename(p) for p in stale) if stale else 'fresh')); sys.exit(1 if stale else 0)
for p, t in out.items(): open(p, 'w', encoding='utf-8').write(t)
print('kitty_doubts: %d rows (%s), %d settled as unused, %d leftovers settled' % (len(rows), ', '.join('%s %d' % (g, n[g]) for g in OPEN), len(unused), len(settled)))
