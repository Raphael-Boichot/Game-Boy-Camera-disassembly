#!/usr/bin/env python3
"""Doubts list of the Hello Kitty symbol file: roms/hello_kitty/disasm/sym_unconclusive_kitty.{csv,md} (generated).

  tools/kitty_doubts.py [--check]

Every name of disasm/sym_names_kitty.csv tagged I or ? must have one row in the hand table disasm/doubts_groups_kitty.csv
(bank, addr, group, why, settle; group = forced only / not run / unused) and every row of that table must be such a name: the
script stops otherwise. Group `unused` is a final verdict (nothing can reach the code, the tag stays I) and is listed apart.
--check compares the two outputs with a fresh run instead of writing them (exit 1 when they differ).
"""
import csv, os, sys, collections, io
KD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'roms', 'hello_kitty', 'disasm')
names = list(csv.DictReader(open(os.path.join(KD, 'sym_names_kitty.csv'), encoding='utf-8')))
doubt = {(r['bank'], r['addr']): r for r in names if r['conf'] != 'C'}
G = {(r['bank'], r['addr']): r for r in csv.DictReader(open(os.path.join(KD, 'doubts_groups_kitty.csv'), encoding='utf-8'))}
miss = [k for k in doubt if k not in G]; extra = [k for k in G if k not in doubt]
if miss or extra:
    sys.exit('kitty_doubts: no group row for %s; group rows without a doubtful name: %s' % (' '.join('%s:%s' % k for k in miss) or '-', ' '.join('%s:%s' % k for k in extra) or '-'))
ORDER = ['forced only', 'not run', 'unused']
bad = [g['group'] for g in G.values() if g['group'] not in ORDER]
if bad: sys.exit('kitty_doubts: unknown group %s' % bad)
rows = sorted((dict(bank=k[0], addr=k[1], name=doubt[k]['name'], conf=doubt[k]['conf'], group=G[k]['group'], evidence=doubt[k]['note'], why_doubtful=G[k]['why'],
               what_would_settle_it=G[k]['settle']) for k in doubt), key=lambda x: (ORDER.index(x['group']), x['bank'], x['addr']))
c = io.StringIO(); w = csv.DictWriter(c, fieldnames=list(rows[0]) if rows else ['bank'], lineterminator='\n'); w.writeheader(); w.writerows(rows)
n = collections.Counter(x['group'] for x in rows)
tags = collections.Counter(r['conf'] for r in names)
L = ['# Doubtful names of the Hello Kitty symbol file\n',
     'Generated by `tools/kitty_doubts.py` from `sym_names_kitty.csv` and the hand table `doubts_groups_kitty.csv` (companion: `sym_unconclusive_kitty.csv`). '
     'Every name not tagged C is here: %d of %d names (C %d / I %d / ? %d). %d are open (%d in modes reached only by forcing the mode byte, %d in states the runs did not reach); '
     '%d are settled as unused (final: nothing can reach them, so no run can confirm them).\n' % (len(rows), len(names), tags['C'], tags['I'], tags['?'],
     n['forced only'] + n['not run'], n['forced only'], n['not run'], n['unused']),
     'The code of every row is read: what each routine does is in the evidence column; the doubt is whether and where the game runs it.\n']
for g in ORDER:
    X = [x for x in rows if x['group'] == g]
    if not X: continue
    L.append('## %s (%d)\n' % (g, len(X)))
    L.append('| address | name | evidence | why doubtful | what would settle it |\n|---|---|---|---|---|')
    for x in X: L.append('| %s:%s | `%s` | %s | %s | %s |' % (x['bank'], x['addr'], x['name'], x['evidence'].replace('|', '/'), x['why_doubtful'], x['what_would_settle_it']))
    L.append('')
md = '\n'.join(L)
out = {os.path.join(KD, 'sym_unconclusive_kitty.csv'): c.getvalue(), os.path.join(KD, 'sym_unconclusive_kitty.md'): md}
if '--check' in sys.argv:
    stale = [p for p, t in out.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != t]
    print('kitty_doubts: %s' % ('stale: ' + ' '.join(os.path.basename(p) for p in stale) if stale else 'fresh')); sys.exit(1 if stale else 0)
for p, t in out.items(): open(p, 'w', encoding='utf-8').write(t)
print('kitty_doubts: %d rows (%s)' % (len(rows), ', '.join('%s %d' % (g, n[g]) for g in ORDER)))
