#!/usr/bin/env python3
"""RAM names of Pocket Camera (Japan) Rev A: table loader, per-site resolver and generator of the two derived files.

  tools/ram_names.py [--names roms/jp_rev_a/disasm/ram_names_jp.csv] [--inc roms/jp_rev_a/disasm/ram_jp.inc] [--sym pocketcamera_jp_ram.sym] [--check]

Source of truth: roms/jp_rev_a/disasm/ram_names_jp.csv (one row per named byte range; the byte-level map and the evidence behind every row are in wram/ and README section 2).
Derived, never edited by hand:
  roms/jp_rev_a/disasm/ram_jp.inc          `DEF wMode EQU $d5ce` lines (INCLUDEd by game.asm after hardware.inc; the names starting with `_` come from hardware.inc itself)
  pocketcamera_jp_ram.sym    the same names as `00:D5CE wMode` for BGB / no$gba (append it to a copy of pocketcamera_jp.sym; mgbdis must NOT read it, it would
                             substitute a name for every operand that equals the address)
--check compares both files with a fresh run and exits 1 on a difference.

Columns of the table: addr (hex), size (bytes), name, scope, tag (C / I / U / ?), desc (the row of the map).
Prefixes: `w` WRAM, `h` HRAM. A name is used as `name` at its first byte and as `name + $off` inside the range.
scope: which instructions may use the row. `*` every bank, `BB` one bank, `BB:AAAA` one routine (the `function` column of roms/jp_rev_a/wram/wram_access.csv), a routine label
(`Bank005_State08`) or `BB@AAAA` one instruction; several separated by `;`. Rows of the overlay area $C000-$D4FF (one address, several buffers: README section 2) carry the
scope of the routines that use that view. For one site the most specific scope wins (instruction, routine, bank, `*`), then the narrowest range."""
import csv, os, re, sys, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


class Row:
    __slots__ = ('addr', 'size', 'name', 'scope', 'tag', 'desc', 'toks')

    def __init__(self, d):
        self.addr = int(d['addr'], 16); self.size = int(d['size']); self.name = d['name']; self.scope = d['scope']; self.tag = d['tag']; self.desc = d['desc']
        self.toks = []
        for t in self.scope.split(';'):
            t = t.strip()
            if t == '*': self.toks.append((3, None, None))
            elif re.fullmatch(r'[0-9A-Fa-f]{2}', t): self.toks.append((2, int(t, 16), None))
            elif re.fullmatch(r'[0-9A-Fa-f]{2}@[0-9A-Fa-f]{4}', t): self.toks.append((0, int(t[:2], 16), int(t[3:], 16)))
            elif re.fullmatch(r'[0-9A-Fa-f]{2}:[0-9A-Fa-f]{4}', t): self.toks.append((1, None, '%02x:%04x' % (int(t[:2], 16), int(t[3:], 16))))
            elif re.fullmatch(r'[A-Za-z_]\w*', t): self.toks.append((1, None, t.lower()))
            else: raise ValueError('bad scope %r in row %s' % (t, d['name']))

    @property
    def end(self): return self.addr + self.size

    def rank(self, bank, pc, fn):
        best = None
        for k, b, x in self.toks:
            if k == 3: r = 3
            elif k == 2: r = 2 if b == bank else None
            elif k == 0: r = 0 if (b == bank and x == pc) else None
            else: r = 1 if (fn is not None and x == fn.lower()) else None
            if r is not None and (best is None or r < best): best = r
        return best


def load(path=None):
    path = path or os.path.join(ROOT, 'roms', 'jp_rev_a', 'disasm', 'ram_names_jp.csv')
    rows = [Row(d) for d in csv.DictReader(open(path, encoding='utf-8'))]
    names = {}
    for r in rows:
        if r.name in names: raise ValueError('duplicate name %s' % r.name)
        names[r.name] = r
    return rows


class Resolver:
    def __init__(self, rows):
        self.rows = rows

    def resolve(self, bank, pc, fn, addr):
        """(row, offset) for the instruction at bank:pc (routine fn) that uses the RAM address addr; None when no row of that scope covers it;
        raises on a tie between two rows of the same rank and size"""
        best = None; tie = False
        for r in self.rows:
            if not (r.addr <= addr < r.end): continue
            k = r.rank(bank, pc, fn)
            if k is None: continue
            key = (k, r.size)
            if best is None or key < best[0]: best = (key, r); tie = False
            elif key == best[0]: tie = True
        if best is None: return None
        if tie: raise ValueError('ambiguous %02x:%04x (%s) %04x' % (bank, pc, fn, addr))
        r = best[1]
        return r, addr - r.addr


def ref(row, off):
    """source text of a reference to row + off"""
    return row.name if off == 0 else '%s + $%x' % (row.name, off)


def inc_text(rows):
    out = ['; Pocket Camera (Japan) Rev A: RAM names. Generated by tools/ram_names.py from roms/jp_rev_a/disasm/ram_names_jp.csv, do not edit.',
           '; INCLUDE after hardware.inc. w = WRAM ($C000-$DFFF), h = HRAM ($FF80-$FFFE). Tags: C code-traced, I inferred, U unused / unknown.', '']
    seen = set()
    for r in sorted(rows, key=lambda r: (r.addr, -r.size, r.name)):
        if r.name.startswith('_') or r.name in seen: continue
        seen.add(r.name)
        out.append('DEF %-26s EQU $%04x ; %s %d  %s' % (r.name, r.addr, r.tag, r.size, r.desc.replace('\n', ' ')[:90]))
    return '\n'.join(out) + '\n'


def sym_text(rows):
    out = ['; Pocket Camera (Japan) Rev A: RAM labels for BGB / no$gba. Generated by tools/ram_names.py from disasm/ram_names_jp.csv.']
    for r in sorted(rows, key=lambda r: (r.addr, r.name)):
        if r.name.startswith('_'): continue
        out.append('00:%04X %s' % (r.addr, r.name))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--names', default=os.path.join(ROOT, 'roms', 'jp_rev_a', 'disasm', 'ram_names_jp.csv'))
    ap.add_argument('--inc', default=os.path.join(ROOT, 'roms', 'jp_rev_a', 'disasm', 'ram_jp.inc'))
    ap.add_argument('--sym', default=os.path.join(ROOT, 'roms', 'jp_rev_a', 'pocketcamera_jp_ram.sym'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    rows = load(a.names)
    want = ((a.inc, inc_text(rows)), (a.sym, sym_text(rows)))
    if a.check:
        bad = 0
        for p, t in want:
            if not os.path.exists(p) or open(p, encoding='utf-8', newline='').read() != t: print('differs:', p); bad += 1
        sys.exit(1 if bad else 0)
    for p, t in want:
        with open(p, 'w', encoding='utf-8', newline='\n') as f: f.write(t)
    print('%d rows: %s, %s' % (len(rows), a.inc, a.sym))
