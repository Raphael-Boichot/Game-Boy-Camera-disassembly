#!/usr/bin/env python3
"""Compare the executed bytes of the prototype's core runs with its static trace (L2).

  tools/proto_observed.py PROTO.gb roms/prototype_debagame/trace/trace_proto.json roms/prototype_debagame/trace/cov_proto_runs.npz \
        [--merge COV_DIR/cov.npz ...] [--report roms/prototype_debagame/trace/observed_proto.md]

--merge first merges the cov.npz of tools/proto_coverage.py runs into the runs file (exec: 1 where any run executed the byte;
dread: max; reader: the first non-zero in the order given), so the committed file holds the union of the runs.
Then, per traced instruction (trace/trace_proto.json): ran = its first byte was executed in at least one run. The report gives:
  * instructions and code bytes of the trace that ran / did not run (by routine block: a run of traced instructions that did
    not run, between instructions that did), and the GAME_SEQ handler each block lies under is not decided here;
  * executed bytes outside the trace (would mean a path the trace missed: listed one by one, expected none);
  * the banks in which any byte was executed (expected: $00 only, the trace's finding).
Prints `proto_observed: N of M instructions ran, X of Y code bytes, Z executed bytes outside the trace, banks executed ...`.
"""
import sys, json, argparse, collections
import numpy as np
ap = argparse.ArgumentParser()
ap.add_argument('rom'); ap.add_argument('trace'); ap.add_argument('runs'); ap.add_argument('--merge', nargs='*', default=[]); ap.add_argument('--report', default=None)
a = ap.parse_args()
if a.merge:
    ex = dr = rd = None
    for f in a.merge:
        z = np.load(f)
        if ex is None: ex, dr, rd = (z['exec'] > 0).astype(np.uint8), z['dread'].copy(), z['reader'].copy()
        else:
            ex |= (z['exec'] > 0).astype(np.uint8); dr = np.maximum(dr, z['dread']); rd = np.where(rd != 0, rd, z['reader'])
    np.savez_compressed(a.runs, exec=ex, dread=dr, reader=rd)
z = np.load(a.runs); ex = z['exec'] > 0
T = json.load(open(a.trace))
def off(k): b, ad = int(k[:2], 16), int(k[3:], 16); return ad if ad < 0x4000 else b * 0x4000 + ad - 0x4000
code = sorted((off(k), n, k) for k, n in T['code'].items())
traced = np.zeros(len(ex), bool)
for o, n, _ in code: traced[o:o + n] = True
ran = [(o, n, k) for o, n, k in code if ex[o]]
notran = [(o, n, k) for o, n, k in code if not ex[o]]
outside = np.nonzero(ex & ~traced)[0]
banks = sorted(set(int(x) >> 14 for x in np.nonzero(ex)[0]))
blocks = []       # consecutive not-run instructions
for o, n, k in notran:
    if blocks and blocks[-1][1] == o: blocks[-1][1] = o + n; blocks[-1][2] += 1
    else: blocks.append([o, o + n, 1, k])
nb_ran = sum(n for _, n, _ in ran); nb_all = sum(n for _, n, _ in code)
print('proto_observed: %d of %d instructions ran, %d of %d code bytes, %d executed bytes outside the trace, banks executed %s, %d blocks not run' % (
    len(ran), len(code), nb_ran, nb_all, len(outside), ' '.join('%02X' % b for b in banks), len(blocks)))
if a.report:
    with open(a.report, 'w') as f:
        f.write('# Prototype: what the core runs executed, against the static trace\n\nGenerated by `tools/proto_observed.py` from `trace/cov_proto_runs.npz` (the union of the core runs of `tools/proto_coverage.py`). ')
        f.write('%d of %d traced instructions ran (%d of %d code bytes); %d executed bytes lie outside the trace; banks executed: %s.\n\n' % (
            len(ran), len(code), nb_ran, nb_all, len(outside), ' '.join('$%02X' % b for b in banks)))
        if len(outside):
            f.write('## Executed outside the trace\n\n' + ', '.join('%02X:%04X' % (o >> 14, o if o < 0x4000 else 0x4000 + (o & 0x3FFF)) for o in outside[:400]) + '\n\n')
        f.write('## Traced code that never ran (%d blocks)\n\nA block is a run of traced instructions none of which ran. Not run is not dead: it is what these inputs and saves did not reach.\n\n| start | end | instructions | bytes |\n|---|---|---|---|\n' % len(blocks))
        for s, e, n, k in blocks: f.write('| %s | 00:%04X | %d | %d |\n' % (k, e - 1, n, e - s))
