#!/usr/bin/env python3
"""Character map of the Japanese name / comment charset for rgbasm (README 16.27, L6 text table).

  tools/charmap_jp.py [--csv roms/jp_rev_a/disasm/charset_jp.csv] [--out roms/jp_rev_a/disasm/charmap_jp.inc] [--check]

Writes `NEWCHARMAP kana`, one `CHARMAP "<char>", $code` per row of roms/jp_rev_a/disasm/charset_jp.csv (codes $01-$F5; the glyph of code c is the 8 x 16 pair at 2A:4000 + (c-1) x 32,
Glyph_LoadFromCharCode 09:4802) and `SETCHARMAP main`, so the default map stays the one of the ASCII strings (`MAIN PASS`, `Magic`).  The listing switches
to it with `PUSHC kana` / `POPC` around the tables of roms/jp_rev_a/disasm/text_tables_jp.csv (tools/sym_fix.py --const).  Never edit the output by hand."""
import csv, os, sys, argparse
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def text(rows):
    L = ['; Pocket Camera (Japan) Rev A: character map of the name / comment charset. Generated by tools/charmap_jp.py from roms/jp_rev_a/disasm/charset_jp.csv, do not edit.',
         '; Use it with PUSHC kana ... POPC; the default map (main) is left for the ASCII strings. Tags: C seen in BGB or read from the code, I inferred.', '',
         'NEWCHARMAP kana']
    for r in rows:
        ch = r['char'].replace('\\', '\\\\').replace('"', '\\"')
        L.append('CHARMAP "%s", $%s ; %s, %s' % (ch, r['code'].upper(), r['class'], r['evidence']))
    L += ['SETCHARMAP main', '']
    return '\n'.join(L)
if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--csv', default=os.path.join(ROOT, 'roms', 'jp_rev_a', 'disasm', 'charset_jp.csv'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'roms', 'jp_rev_a', 'disasm', 'charmap_jp.inc')); ap.add_argument('--check', action='store_true'); a = ap.parse_args()
    rows = list(csv.DictReader(open(a.csv, encoding='utf-8')))
    if len({r['char'] for r in rows}) != len(rows): sys.exit('charset_jp.csv: two codes share a character')
    t = text(rows)
    if a.check: sys.exit(0 if os.path.exists(a.out) and open(a.out, encoding='utf-8', newline='').read() == t else 1)
    open(a.out, 'w', encoding='utf-8', newline='\n').write(t); print('%d characters: %s' % (len(rows), a.out))
